#!/usr/bin/env python3
"""Reproduce the SDK-free ports from the vendored, unmodified Airwindows sources."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
for name in ('ChimeyGuitar', 'ChimeyGuitar2', 'ChimeyDeluxe', 'kWoodRoom', 'WoodenBox'):
    src = root / 'third_party' / 'airwindows' / name
    header = (src / f'{name}.h').read_text()
    state = header.split('private:')[1].split('float A;')[1].split('};\n\n#endif')[0]
    state = 'float A;' + state
    ctor = (src / f'{name}.cpp').read_text().split('AudioEffectX(audioMaster, kNumPrograms, kNumParameters)\n{')[1].split('_canDo.insert')[0]
    ctor = re.sub(r'fpdL = 1.0; while \(fpdL < 16386\) fpdL = rand\(\)\*UINT32_MAX;', 'fpdL = 0x12345678u;', ctor)
    ctor = re.sub(r'fpdR = 1.0; while \(fpdR < 16386\) fpdR = rand\(\)\*UINT32_MAX;', 'fpdR = 0x87654321u;', ctor)
    cls = name + 'Engine'
    constants = header[header.index('const int d3A' if name == 'kWoodRoom' else 'const int d4A'):header.index('const int kNumPrograms')] if name in ('kWoodRoom', 'WoodenBox') else ''
    api = f'''// Airwindows MIT DSP; see THIRD_PARTY.md. Generated by scripts/port-engines.py.
#pragma once
#include <cstdint>
#include <cmath>
{constants + chr(10) if constants else ''}class {cls} {{
public:
    {cls}() {{ reset(44100.); }}
    void reset(double rate);
    void setParameter(int index, float value) {{
        if (!std::isfinite(value)) return;
        value = value < 0 ? 0 : value > 1 ? 1 : value;
        switch(index) {{
'''
    api += ''.join(f'            case {i}: {c} = value; break;\n' for i,c in enumerate('ABCDEF' if name == 'kWoodRoom' else 'ABC' if name == 'WoodenBox' else 'ABCDEFGHIJ'))
    api += f'''            default: break;
        }}
    }}
    void processReplacing(float**, float**, int);
    void processDoubleReplacing(double**, double**, int);
private:
    double getSampleRate() const {{ return sampleRate; }}
    double sampleRate = 44100.;
    {state}
}};
'''
    proc = (src / f'{name}Proc.cpp').read_text()
    proc = proc[proc.index(f'void {name}::processReplacing'):].replace(f'{name}::', f'{cls}::').replace('VstInt32', 'int')
    (root / 'Source' / f'{cls}.h').write_text(api)
    (root / 'Source' / f'{cls}.cpp').write_text(f'// Airwindows MIT DSP; see THIRD_PARTY.md. Generated by scripts/port-engines.py.\n#include "{cls}.h"\nvoid {cls}::reset(double rate) {{\n sampleRate = rate > 0 ? rate : 44100.;\n{ctor}\n}}\n{proc}')
